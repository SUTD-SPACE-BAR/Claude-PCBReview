"""The BOM against the schematic — what will actually be built.

The brief, 2026-08-03: *"You mentioned dropped components a few times. Maybe
we should compare the list of components generated by the auditor against the
BOM or the schematic component list."*

`parity.py` already compares the **schematic against the board**. This compares
the schematic against the **BOM**, which is a third document and the one the
assembler actually reads. A part can be right in the schematic, right on the
board, and wrong in the file that gets sent to the fab — and nothing else here
would notice.

That is not hypothetical. On the board that prompted this, the schematic's
catch diode for a buck converter is an SS34 (40 V) and the BOM line for the
same designator is a 1N5820 (**20 V**). Both are 3 A Schottkys, both fit the
footprint, and the BOM is what gets ordered.

Three comparisons, in order of how badly each one bites:

* **In the schematic, absent from the BOM.** The board will be assembled with
  that part missing. Sometimes deliberate — a DNP, a test point, a mounting
  hole — so `dnp` and `exclude_from_bom` are read and honoured where the
  export carries them.
* **In the BOM, absent from the schematic.** A stale export. The part number
  ordered belongs to a design that no longer exists.
* **Different value for the same designator.** The case above, and the only one
  of the three that both documents claim to describe.

What this does not do
---------------------
It does not judge whether a part number is *correct*, only whether the two
documents agree. Deciding that an SS34 and a 1N5820 are not interchangeable
needs the datasheets, which is the human's job and Claude's to ask for.

It also reads the BOM as **exported**, without assuming which tool wrote it.
KiCad's own exporter, the Fabrication Toolkit plugin and JLCPCB's template all
use different column names for the same three things, so the header is matched
case-insensitively against a list of aliases and the file is refused rather
than guessed at when no reference column can be found.
"""

from __future__ import annotations

import csv
import re
from dataclasses import dataclass, field
from pathlib import Path

#: Column-name aliases, lowercased. Measured against the exports present here:
#: KiCad's own, the Fabrication Toolkit's, and JLCPCB's assembly template.
_REFERENCE_COLUMNS = ("reference", "references", "designator", "designators",
                      "ref", "refdes", "part reference")
_VALUE_COLUMNS = ("value", "val", "comment", "component value")
_QUANTITY_COLUMNS = ("qty", "quantity", "count")
_DNP_COLUMNS = ("dnp", "do not populate", "do not place")
_EXCLUDE_COLUMNS = ("exclude from bom", "exclude_from_bom", "bom exclude")

#: A designator is letters then digits. Everything else in a reference cell —
#: a heading, a total, a stray note — is not a part.
_DESIGNATOR = re.compile(r"^[A-Za-z]+\d+$")


class BomError(Exception):
    """Raised when a BOM file cannot be read as one."""


@dataclass
class BomLine:
    reference: str
    value: str | None = None
    dnp: bool = False
    excluded: bool = False
    row: int = 0


@dataclass
class BomComparison:
    """What the BOM and the schematic disagree about."""
    source_path: object = None
    lines: dict = field(default_factory=dict)
    #: designators in the schematic and not in the BOM, less DNP and excluded
    missing_from_bom: list = field(default_factory=list)
    #: and the ones that are absent for a stated reason
    absent_but_marked: list = field(default_factory=list)
    #: designators in the BOM that the schematic does not have
    not_in_schematic: list = field(default_factory=list)
    #: (reference, schematic value, bom value)
    value_mismatches: list = field(default_factory=list)
    compared: int = 0

    def is_clean(self) -> bool:
        return not (self.missing_from_bom or self.not_in_schematic
                    or self.value_mismatches)

    def summary(self) -> dict:
        return {
            "bom": str(self.source_path) if self.source_path else None,
            "compared": self.compared,
            "bom_lines": len(self.lines),
            "missing_from_bom": self.missing_from_bom,
            "absent_but_marked": self.absent_but_marked,
            "not_in_schematic": self.not_in_schematic,
            "value_mismatches": [
                {"reference": r, "schematic": s, "bom": b}
                for r, s, b in self.value_mismatches],
        }


def _column(header, aliases):
    for index, name in enumerate(header):
        if (name or "").strip().lower() in aliases:
            return index
    return None


def _truthy(cell) -> bool:
    return (cell or "").strip().lower() in ("1", "y", "yes", "true", "dnp", "x")


def load(path) -> dict:
    """Read a BOM CSV into `{reference: BomLine}`. Raises rather than guessing.

    Multi-reference cells (`"C2,C3"`, which is how every exporter groups
    identical parts) are split, so one line becomes several designators.
    """
    path = Path(path)
    if not path.exists():
        raise BomError(f"BOM not found: {path}")
    with path.open(newline="", encoding="utf-8-sig") as handle:
        rows = list(csv.reader(handle))
    if not rows:
        raise BomError(f"{path} is empty")

    header_index = None
    for index, row in enumerate(rows[:10]):
        if _column(row, _REFERENCE_COLUMNS) is not None:
            header_index = index
            break
    if header_index is None:
        raise BomError(
            f"{path} has no reference column — looked for "
            f"{', '.join(_REFERENCE_COLUMNS)} in the first ten rows. Refusing "
            "rather than guessing which column holds the designators")

    header = rows[header_index]
    ref_col = _column(header, _REFERENCE_COLUMNS)
    val_col = _column(header, _VALUE_COLUMNS)
    dnp_col = _column(header, _DNP_COLUMNS)
    exc_col = _column(header, _EXCLUDE_COLUMNS)

    lines: dict[str, BomLine] = {}
    for number, row in enumerate(rows[header_index + 1:], start=header_index + 2):
        if ref_col >= len(row):
            continue
        cell = (row[ref_col] or "").strip().strip('"')
        if not cell:
            continue
        value = (row[val_col].strip() if val_col is not None
                 and val_col < len(row) else None)
        dnp = _truthy(row[dnp_col]) if dnp_col is not None and dnp_col < len(row) else False
        excluded = (_truthy(row[exc_col])
                    if exc_col is not None and exc_col < len(row) else False)
        for reference in (part.strip() for part in cell.split(",")):
            if not _DESIGNATOR.match(reference):
                continue
            lines[reference] = BomLine(reference=reference, value=value or None,
                                       dnp=dnp, excluded=excluded, row=number)
    if not lines:
        raise BomError(f"{path} has a reference column but no designators in it")
    return lines


def _normalise_value(text) -> str:
    """Values compared loosely — whitespace and case only.

    Deliberately not unit-aware. `4.7nF` and `4n7` are the same part and this
    will call them different; that is a false positive a human dismisses in a
    second, and the alternative is a unit parser that quietly calls `1N5820`
    and `SS34` the same because neither parses.
    """
    return re.sub(r"\s+", " ", (text or "")).strip().lower()


def compare(schematic, bom_lines: dict, source_path=None) -> BomComparison:
    """Compare a schematic's components against a BOM's designators."""
    result = BomComparison(source_path=source_path, lines=bom_lines)
    on_schematic = {c.reference: c for c in schematic.components}

    for reference, component in sorted(on_schematic.items()):
        line = bom_lines.get(reference)
        if line is None:
            if component.dnp:
                result.absent_but_marked.append(f"{reference} (DNP)")
            else:
                result.missing_from_bom.append(reference)
            continue
        result.compared += 1
        if line.dnp or line.excluded:
            continue
        left = _normalise_value(component.value)
        right = _normalise_value(line.value)
        if left and right and left != right:
            result.value_mismatches.append(
                (reference, component.value, line.value))

    result.not_in_schematic = sorted(set(bom_lines) - set(on_schematic))
    return result


#: Where a BOM actually lives, in the order to look. `<board>.csv` first,
#: because that is the name this project documents and the one a user who was
#: told to produce one will use. Everything after it is where KiCad's own
#: fabrication toolkits put theirs without asking.
#:
#: Only the first pattern was checked originally, so on a project whose
#: fabrication plugin had written `production/bom.csv` the check reported *"no
#: BOM was compared — none was supplied or found beside the board"* while a
#: perfectly good BOM sat one directory down. The user copied it, ran the
#: check, found a real defect, and deleted the copy — which is three steps
#: that a glob removes.
_BOM_PATTERNS = (
    "{stem}.csv",
    "production/{stem}.csv",
    "production/bom.csv",
    "production/*bom*.csv",
    "bom/{stem}.csv",
    "bom/bom.csv",
    "{stem}-bom.csv",
    "{stem}_bom.csv",
    "*bom*.csv",
)


def find_bom(board_path) -> Path | None:
    """The BOM for this board, or `None`. First match in `_BOM_PATTERNS` wins.

    Returns the path so the caller can *say which file it used* — an
    auto-discovered input that is never named is how the wrong BOM gets
    compared without anyone noticing.

    **Absolute, always.** It used to record whatever string it was handed, so a
    `bom_parity` finding named `bom.csv` when the caller had used a relative
    board path and the full path when it had not — two findings differing
    between two baselines taken from different working directories, with no
    measurement changed. §52.3 fixed exactly this in `extract.py` and missed
    here, and this was the last known source of a spurious baseline diff.
    """
    board = Path(board_path).resolve()
    for pattern in _BOM_PATTERNS:
        expanded = pattern.format(stem=board.stem)
        if "*" in expanded:
            matches = sorted(board.parent.glob(expanded))
            if matches:
                return matches[0]
        else:
            candidate = board.parent / expanded
            if candidate.exists():
                return candidate
    return None


def default_path(board_path):
    """Where a board's BOM lives, if it has one beside it.

    Kept as the canonical *name* — `find_bom` is what discovery should use.
    """
    return Path(board_path).with_suffix(".csv")


def coverage(comparison: BomComparison | None) -> dict:
    """What this check had to work with. Print it before believing a zero."""
    if comparison is None:
        return {"bom": None, "compared": 0,
                "note": "no BOM was supplied or found beside the board"}
    return comparison.summary()
